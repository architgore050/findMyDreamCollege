@dataclass
class AddOutcome:
    status: str  # "verified" | "unverified"
    dry_run: bool
    entry_id: str
    predicate: str
    entry_path: Path | None
    fixture_path: Path | None
    sidecar_path: Path | None
    proof: Proof
    reasons: list[str]
    entry: dict[str, Any]
    fixture_sha256: str


def execute_add(plan: AddPlan, candidate: PrintedCandidate, meta: Any, *, now: date) -> AddOutcome:
    """Prove the candidate and write fixture + sidecar + entry YAML (or unverified)."""
    inputs = plan.inputs
    proof = prove_quote(
        plan.fixture_text,
        candidate.quote,
        context=inputs.context,
        row_label=inputs.row_label,
    )
    fixture_bytes = plan.fixture_text.encode("utf-8")
    fixture_sha256 = sha256_bytes(fixture_bytes)

    entry_dict, row_dict = _assemble_entry(plan, candidate, meta, proof, now, fixture_sha256)
    # The loader's own schema is the gate: an entry that would not load is never written.
    try:
        GoldenEntry.model_validate(entry_dict)
    except Exception as exc:
        raise CuratorError(f"assembled entry failed loader validation: {exc}") from exc

    outcome = AddOutcome(
        status=row_dict["status"],
        dry_run=inputs.dry_run,
        entry_id=plan.entry_id,
        predicate=inputs.predicate,
        entry_path=None if inputs.dry_run else plan.entry_path,
        fixture_path=None if inputs.dry_run else plan.fixture_path,
        sidecar_path=None,
        proof=proof,
        reasons=[] if proof.ok else list(proof.problems),
        entry=entry_dict,
        fixture_sha256=fixture_sha256,
    )
    if inputs.dry_run:
        return outcome

    _write_outputs(plan, meta, entry_dict, fixture_bytes, fixture_sha256, now)
    sidecar_path = plan.fixture_path.with_suffix(".json")
    outcome.sidecar_path = sidecar_path
    return outcome


def _assemble_entry(
    plan: AddPlan,
    candidate: PrintedCandidate,
    meta: Any,
    proof: Proof,
    now: date,
    fixture_sha256: str,
) -> tuple[dict[str, Any], dict[str, Any]]:
    inputs = plan.inputs
    retrieved_at = now.isoformat()
    row_dict: dict[str, Any]
    if proof.ok:
        row_dict = {
            "value": plan.value,
            "unit": inputs.unit,
            "quote": candidate.quote,
            "status": "verified",
        }
        if inputs.printed_value is not None:
            row_dict["printed_value"] = inputs.printed_value.strip()
        if inputs.printed_unit is not None:
            row_dict["printed_unit"] = inputs.printed_unit.strip()
        if proof.disambiguation == "context_row":
            row_dict["context"] = inputs.context
            row_dict["disambiguation"] = "context_row"
            row_dict["row"] = {
                "row_label": inputs.row_label,
                "column_header": inputs.column_header,
                "value_cell": inputs.value_cell
                or (inputs.printed_value.strip() if inputs.printed_value else str(plan.value)),
                "table_page": inputs.table_page or inputs.page,
            }
    else:
        attempted = ""
        if inputs.context:
            attempted = f" (attempted context {inputs.context!r})"
        row_dict = {
            "value": None,
            "unit": None,
            "quote": candidate.quote,
            "status": "unverified",
            "note": "; ".join(proof.problems) + attempted,
        }

    provenance = (
        f"Fixture generated by `fmd golden add` from {inputs.source} "
        f"(page {inputs.page}, source sha256 {meta.sha256}, pdftext {meta.tool_version}); "
        f"fixture sha256 {fixture_sha256}. Quotes are extracted from the source, never typed."
    )
    notes = " ".join(part for part in (inputs.notes, provenance) if part)

    entry_dict: dict[str, Any] = {
        "schema_version": 1,
        "id": plan.entry_id,
        "institution": inputs.institution,
        "programme": inputs.programme,
        "state": inputs.state,
        "source_url": inputs.source_url or (inputs.source if _is_url(inputs.source) else None),
        "retrieved_at": retrieved_at,
        "fixture": plan.fixture_rel,
        "llm_fixture": None,
        "family": None,  # replay entries need a recorded guided-JSON fixture; hand-added later
        "notes": notes,
        "expected": {inputs.predicate: row_dict},
    }
    return entry_dict, row_dict


def _write_outputs(
    plan: AddPlan,
    meta: Any,
    entry_dict: dict[str, Any],
    fixture_bytes: bytes,
    fixture_sha256: str,
    now: date,
) -> None:
    inputs = plan.inputs
    existing_entry_path = plan.entry_path
    if existing_entry_path.exists():
        entry_dict = _merge_into_existing(plan, existing_entry_path, entry_dict, fixture_bytes)

    plan.fixture_path.parent.mkdir(parents=True, exist_ok=True)
    if plan.fixture_path.exists():
        current = plan.fixture_path.read_bytes()
        if current != fixture_bytes:
            raise CuratorError(
                f"fixture {plan.fixture_path} already exists with different bytes "
                f"(sha256 {_hash(current)} vs generated {fixture_sha256}); the source document "
                "changed — investigate before overwriting"
            )
    plan.fixture_path.write_bytes(fixture_bytes)

    sidecar = {
        "schema": SIDECAR_SCHEMA,
        "entry_id": plan.entry_id,
        "predicate": inputs.predicate,
        "fixture": plan.fixture_rel,
        "fixture_sha256": fixture_sha256,
        "source": inputs.source,
        "source_url": entry_dict.get("source_url"),
        "source_sha256": meta.sha256,
        "retrieved_at": entry_dict.get("retrieved_at"),
        "page": inputs.page,
        "pages": meta.page_count,
        "tool": meta.tool,
        "tool_version": meta.tool_version,
        "row_status": entry_dict["expected"][inputs.predicate]["status"],
        "created_at": datetime.now(UTC).isoformat(timespec="seconds"),
    }
    sidecar_path = plan.fixture_path.with_suffix(".json")
    sidecar_path.write_text(
        json.dumps(sidecar, indent=2, sort_keys=True, ensure_ascii=True) + "\n", encoding="utf-8"
    )

    existing_entry_path.parent.mkdir(parents=True, exist_ok=True)
    header = (
        f"# {GENERATED_MARKER} on {now.isoformat()}; re-validated by `fmd golden check`.\n"
        f"# Source: {inputs.source} page {inputs.page}; source sha256 {meta.sha256}.\n"
        f"# Fixture: {plan.fixture_rel} (sha256 {fixture_sha256}).\n"
    )
    body = yaml.safe_dump(
        _prune(entry_dict),
        sort_keys=False,
        allow_unicode=True,
        default_flow_style=False,
        width=100,
    )
    tmp = existing_entry_path.with_suffix(".yaml.tmp")
    tmp.write_text(header + body, encoding="utf-8")
    os.replace(tmp, existing_entry_path)


def _merge_into_existing(
    plan: AddPlan, entry_path: Path, entry_dict: dict[str, Any], fixture_bytes: bytes
) -> dict[str, Any]:
    """Add one predicate to an existing tool-generated entry (one fixture per entry)."""
    text = entry_path.read_text(encoding="utf-8")
    if GENERATED_MARKER not in text:
        raise CuratorError(
            f"entry {entry_path} was not generated by `fmd golden add`; append further "
            "predicates to hand-curated entries by editing the YAML, then run `fmd eval`"
        )
    try:
        existing = GoldenEntry.model_validate(yaml.safe_load(text))
    except Exception as exc:
        raise CuratorError(f"existing entry {entry_path} does not load: {exc}") from exc
    if existing.fixture != plan.fixture_rel:
        raise CuratorError(
            f"entry {existing.id} already binds fixture {existing.fixture!r}; a golden entry "
            "has exactly one fixture, so rows from another page/document need their own entry id"
        )
    on_disk = plan.fixture_path.read_bytes() if plan.fixture_path.exists() else None
    if on_disk is not None and on_disk != fixture_bytes:
        raise CuratorError(
            f"committed fixture {plan.fixture_path} differs from the regenerated page text; "
            "the source document changed — resolve that before adding rows"
        )
    if plan.inputs.predicate in existing.expected and not plan.inputs.force:
        raise CuratorError(
            f"predicate {plan.inputs.predicate!r} already exists on entry {existing.id}; "
            "pass --force to replace it"
        )
    merged = existing.model_dump()
    merged["expected"][plan.inputs.predicate] = entry_dict["expected"][plan.inputs.predicate]
    return merged


def _prune(node: Any) -> Any:
    """Drop schema-default None/[] noise, but keep explicit value/quote nulls."""
    if isinstance(node, dict):
        return {
            key: (None if value is None and key in {"value", "quote"} else _prune(value))
            for key, value in node.items()
            if not (value is None and key not in {"value", "quote"})
            and not (value == [] and key not in {"value", "quote"})
        }
    if isinstance(node, list):
        return [_prune(item) for item in node]
    return node


def _is_url(source: str) -> bool:
    return source.startswith(("http://", "https://"))


def _hash(data: bytes) -> str:
    import hashlib

    return hashlib.sha256(data).hexdigest()


