@dataclass
class CheckReport:
    payload: dict[str, Any]
    problems: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.problems

    def as_dict(self) -> dict[str, Any]:
        return {**self.payload, "ok": self.ok}


def check_golden(golden_dir: str | Path, *, root: str | Path | None = None) -> CheckReport:
    """Offline re-validation of a golden directory (no network, no DB)."""
    from fmd.eval.golden import GoldenError, load_golden

    base = Path(root) if root is not None else Path.cwd()
    directory = Path(golden_dir)
    payload: dict[str, Any] = {"golden_dir": str(directory)}
    try:
        golden = load_golden(directory, root=base)
    except GoldenError as exc:
        payload["problems"] = list(exc.problems)
        return CheckReport(payload=payload, problems=list(exc.problems))

    payload["entries"] = len(golden.entries)
    payload["verified_rows"] = golden.verified_rows
    payload["unverified_rows"] = golden.unverified_rows
    payload["by_family"] = _by_family(golden)
    payload["by_traceability"] = {
        kind: sum(1 for trace in golden.traces if trace.traceability == kind)
        for kind in ("fixture", "citation", "unverified")
    }

    fixture_report, fixture_problems = _check_fixtures(golden, base)
    payload["fixtures"] = fixture_report
    context_checks, context_problems = _check_contexts(golden, base)
    payload["context_checks"] = context_checks
    duplicate_failures, duplicate_warnings = _check_duplicates(golden)
    payload["duplicates"] = {"failures": duplicate_failures, "warnings": duplicate_warnings}
    problems = fixture_problems + context_problems + duplicate_failures
    payload["problems"] = problems
    return CheckReport(payload=payload, problems=problems)


def _by_family(golden: Any) -> dict[str, dict[str, int]]:
    families: dict[str, dict[str, int]] = {}
    for entry in golden.entries:
        label = entry.family or "(no family: loader checks only)"
        bucket = families.setdefault(label, {"entries": 0, "verified": 0, "unverified": 0})
        bucket["entries"] += 1
        bucket["verified"] += len(entry.verified_rows)
        bucket["unverified"] += len(entry.unverified_rows)
    return families


def _check_fixtures(golden: Any, base: Path) -> tuple[list[dict[str, Any]], list[str]]:
    from fmd.eval.pdfpage import sha256_bytes

    report: list[dict[str, Any]] = []
    problems: list[str] = []
    seen: set[str] = set()
    for entry in golden.entries:
        if not entry.fixture or entry.fixture in seen:
            continue
        seen.add(entry.fixture)
        path = base / entry.fixture
        item: dict[str, Any] = {"fixture": entry.fixture, "entries": [entry.id]}
        if not path.is_file():
            item["present"] = False
            item["match"] = None
            problems.append(f"{entry.id}: fixture {entry.fixture!r} does not exist")
            report.append(item)
            continue
        item["present"] = True
        actual = sha256_bytes(path.read_bytes())
        item["sha256"] = actual
        sidecar_path = path.with_suffix(".json")
        recorded: dict[str, Any] | None = None
        if sidecar_path.is_file():
            try:
                recorded = json.loads(sidecar_path.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError) as exc:
                problems.append(
                    f"{entry.id}: fixture metadata {sidecar_path.name} is unreadable: {exc}"
                )
        item["recorded_sha256"] = (recorded or {}).get("fixture_sha256")
        item["source_sha256"] = (recorded or {}).get("source_sha256")
        item["source_url"] = (recorded or {}).get("source_url")
        item["retrieved_at"] = (recorded or {}).get("retrieved_at")
        item["sidecar"] = sidecar_path.name if sidecar_path.is_file() else None
        if item["recorded_sha256"] is None:
            item["match"] = None  # pre-tool fixture: recorded by hand, nothing to compare
        elif item["recorded_sha256"] != actual:
            item["match"] = False
            problems.append(
                f"{entry.id}: fixture {entry.fixture!r} sha256 {actual} does not match the "
                f"recorded {item['recorded_sha256']} — the fixture was edited after curation"
            )
        else:
            item["match"] = True
        report.append(item)
    return report, problems


def _check_contexts(golden: Any, base: Path) -> tuple[list[dict[str, Any]], list[str]]:
    checks: list[dict[str, Any]] = []
    problems: list[str] = []
    for entry in golden.entries:
        if not entry.fixture:
            continue
        fixture_path = base / entry.fixture
        text = None
        if fixture_path.is_file():
            try:
                text = fixture_path.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                text = None
        for name, row in entry.expected.items():
            if row.context is None:
                if row.disambiguation is not None:
                    problems.append(
                        f"{entry.id}.{name}: disambiguation {row.disambiguation!r} without a "
                        "context cannot resolve"
                    )
                continue
            if row.status == "unverified":
                checks.append(
                    {
                        "row": f"{entry.id}.{name}",
                        "ok": None,
                        "detail": "unverified row; context kept as curation intent, not checked",
                    }
                )
                continue
            if row.expectation != "value":
                # The loader never resolves a context for abstain/reject rows.
                checks.append(
                    {
                        "row": f"{entry.id}.{name}",
                        "ok": None,
                        "detail": f"{row.expectation} row; the loader does not resolve context",
                    }
                )
                continue
            if text is None:
                problems.append(
                    f"{entry.id}.{name}: fixture {entry.fixture!r} is not readable text; "
                    "the context cannot be re-checked"
                )
                continue
            proof = prove_quote(
                text,
                row.quote or "",
                context=row.context,
                row_label=row.row.row_label if row.row else None,
            )
            checks.append(
                {
                    "row": f"{entry.id}.{name}",
                    "ok": proof.ok,
                    "disambiguation": proof.disambiguation,
                    "detail": proof.detail,
                    "problems": proof.problems,
                }
            )
            problems.extend(f"{entry.id}.{name}: {problem}" for problem in proof.problems)
    return checks, problems


def _check_duplicates(golden: Any) -> tuple[list[str], list[str]]:
    """Return ``(hard failures, warnings)`` — failures make ``check`` exit non-zero."""
    exact: dict[tuple, list[str]] = {}
    warned: dict[tuple, list[str]] = {}
    failures: list[str] = []
    warnings: list[str] = []
    for entry in golden.entries:
        for name, row in entry.expected.items():
            exact_key = (
                entry.fixture,
                name,
                _scalar_key(row.value),
                row.quote,
                row.context,
            )
            exact.setdefault(exact_key, []).append(entry.id)
            warned_key = (entry.institution.strip().lower(), name, _scalar_key(row.value))
            warned.setdefault(warned_key, []).append(entry.id)
    for key, ids in exact.items():
        if len(set(ids)) > 1:
            fixture, predicate, value, quote, context = key
            failures.append(
                f"duplicate predicate row across entries {sorted(set(ids))}: "
                f"fixture={fixture!r} predicate={predicate!r} value={value!r} "
                f"quote={quote!r} context={context!r}"
            )
    for key, ids in warned.items():
        unique_ids = sorted(set(ids))
        if len(unique_ids) > 1:
            institution, predicate, value = key
            warnings.append(
                f"same predicate/entity on {len(unique_ids)} entries {unique_ids}: "
                f"institution={institution!r} predicate={predicate!r} value={value!r} "
                "(fine across documents; verify it is not a copy-paste duplicate)"
            )
    return failures, warnings


def _scalar_key(value: Any) -> str:
    if isinstance(value, bool):
        return "bool:true" if value else "bool:false"
    if isinstance(value, float):
        return f"num:{value!r}"
    return repr(value)


