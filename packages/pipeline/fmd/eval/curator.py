def row_gate(row: GoldenValue) -> str:
    """What this row gates, in the same terms the eval report uses."""
    if row.status == "unverified":
        return "gates nothing: excluded from every accuracy metric until a human verifies it"
    if row.expectation == "abstain":
        return "gates abstention correctness"
    if row.expectation == "reject":
        return "gates rejection correctness"
    if row.context is not None:
        return "gates extraction accuracy + row attribution (wrong-row is a false positive)"
    return "gates extraction accuracy (span/value/unit)"


def entry_gate(entry: GoldenEntry) -> str:
    if entry.family:
        return "canary replay: claims_hash + drift, plus the row gates below"
    return "loader fixture checks only; not replayed, so its rows enter no accuracy metric"


def list_golden(golden_dir: str | Path, *, root: str | Path | None = None) -> dict[str, Any]:
    """Entries with status and what each gates (offline; never invents rows)."""
    from fmd.eval.golden import load_golden

    golden = load_golden(golden_dir, root=root)
    entries = []
    for entry in golden.entries:
        measured = bool(entry.family and entry.fixture and entry.llm_fixture)
        rows = []
        for name, row in entry.expected.items():
            rows.append(
                {
                    "predicate": name,
                    "status": row.status,
                    "expectation": row.expectation,
                    "value": row.value if row.status == "verified" else None,
                    "unit": row.unit,
                    "quote": row.quote,
                    "context": row.context,
                    "disambiguation": row.disambiguation,
                    "traceability": _traceability(entry, row),
                    "gate": row_gate(row),
                }
            )
        entries.append(
            {
                "id": entry.id,
                "institution": entry.institution,
                "programme": entry.programme,
                "state": entry.state,
                "family": entry.family,
                "fixture": entry.fixture,
                "source_url": entry.source_url,
                "retrieved_at": entry.retrieved_at,
                "measured": measured,
                "entry_gate": entry_gate(entry),
                "verified_rows": len(entry.verified_rows),
                "unverified_rows": len(entry.unverified_rows),
                "rows": rows,
            }
        )
    return {
        "golden_dir": str(golden_dir),
        "entries": entries,
        "totals": {
            "entries": len(entries),
            "verified_rows": golden.verified_rows,
            "unverified_rows": golden.unverified_rows,
        },
        "legend": [
            "measured = family + fixture + recorded llm_fixture; replayed as a canary",
            "verified value rows gate extraction accuracy; with a context also row attribution",
            "verified abstain rows gate abstention; reject rows gate rejection correctness",
            "unverified rows are counted but excluded from every accuracy metric until verified",
        ],
    }


def _traceability(entry: GoldenEntry, row: GoldenValue) -> str:
    if row.status == "unverified":
        return "unverified"
    return "fixture" if entry.fixture else "citation"


