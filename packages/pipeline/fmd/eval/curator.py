"""Golden-set curation tool: the logic behind ``fmd golden add/check/list``.

The golden loader (``fmd/eval/golden.py``) is deliberately strict: a verified
quote must resolve in a committed fixture, and a ``context_row`` quote must be
ambiguous globally but unique inside its row block. Hand-writing YAML against
those rules is slow and easy to get wrong, so this module turns the rules into
a tool:

* ``add`` extracts the quote from the source PDF itself (pdftext, see
  :mod:`fmd.eval.pdfpage`), proves uniqueness — and for table rows proves
  ambiguity-without-context plus uniqueness-with-context using exactly the same
  helpers the loader uses — and writes ``verified`` only when every check
  passes. Any failed check writes ``unverified`` with ``value: null`` and a
  reason instead; a silent promotion is impossible because the assembled entry
  is validated against the loader's own pydantic schema before it is written.
* ``check`` re-validates a golden directory offline: fixture presence and
  sha256 (against the metadata sidecar ``add`` writes), row-context
  resolution, duplicate predicate/entity rows, and a verified/unverified
  breakdown by family.
* ``list`` reports every entry with its status and what each row gates.

No golden rows are invented here: the tool only writes what a human picked
from a source document it hashed and extracted itself.
"""

from __future__ import annotations

import json
import os
import re
import unicodedata
from dataclasses import dataclass, field
from datetime import UTC, date, datetime
from pathlib import Path
from typing import Any

import yaml

from fmd.eval.golden import GoldenEntry, GoldenValue
from fmd.eval.pdfpage import sha256_bytes
from fmd.eval.rowctx import inside, occurrence_spans, row_block

FIXTURES_DIRNAME = "fixtures"
PROGRAMMES_DIRNAME = "programmes"
SIDECAR_SCHEMA = "fmd-golden-fixture-meta-v1"
GENERATED_MARKER = "Generated by `fmd golden add`"


class CuratorError(ValueError):
    """A curation request cannot be carried out safely; nothing was written."""


# --------------------------------------------------------------------- scalars


def parse_scalar(raw: str) -> str | int | float | bool:
    """Parse a CLI scalar the way golden YAML expects (int/float/bool/text)."""
    text = raw.strip()
    if not text:
        raise CuratorError("expected value is empty; pass --value (and --unit when it applies)")
    lowered = text.lower()
    if lowered in {"true", "false"}:
        return lowered == "true"
    if lowered in {"null", "none"}:
        raise CuratorError(
            "an expected value cannot be null; omit the row or let a failed proof "
            "write the unverified fallback"
        )
    try:
        return int(text)
    except ValueError:
        pass
    try:
        return float(text)
    except ValueError:
        pass
    if len(text) >= 2 and text[0] == text[-1] and text[0] in {"'", '"'}:
        return text[1:-1]
    return text


def parse_optional(raw: str | None) -> str | None:
    if raw is None:
        return None
    text = raw.strip()
    if text.lower() in {"", "none", "null"}:
        return None
    return text


def slugify(text: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", unicodedata.normalize("NFKD", text).lower())
    slug = re.sub(r"-+", "-", slug).strip("-")
    if not slug:
        raise CuratorError(f"cannot derive an entry id from {text!r}; pass --entry-id")
    return slug


# ---------------------------------------------------------------------- proofs


@dataclass(frozen=True)
class Proof:
    """The loader-equivalent uniqueness/context proof for one quote."""

    ok: bool
    disambiguation: str | None  # "unique" | "context_row" | None when failed
    problems: list[str]
    detail: dict[str, Any]

    @property
    def summary(self) -> str:
        if self.ok:
            return f"disambiguation: {self.disambiguation}"
        return "; ".join(self.problems)


def prove_quote(
    fixture_text: str,
    quote: str,
    *,
    context: str | None = None,
    row_label: str | None = None,
) -> Proof:
    """Mirror the golden loader's quote/context rules on ``fixture_text``.

    A quote with no context must occur exactly once. A table-row claim must
    prove the two facts the loader demands: the quote is ambiguous without the
    context (>= 2 occurrences in the fixture) and unique with it (exactly one
    occurrence inside the context's row block). ``unique`` plus a context is
    rejected as mislabelled, exactly as the loader rejects it.
    """

    detail: dict[str, Any] = {}
    quote_spans = occurrence_spans(fixture_text, quote)
    detail["quote_occurrences"] = len(quote_spans)
    detail["quote_span"] = list(quote_spans[0]) if quote_spans else None
    if not quote_spans:
        return Proof(
            False, None, ["quote does not occur in the fixture text (internal error)"], detail
        )

    if context is None:
        if len(quote_spans) == 1:
            return Proof(True, "unique", [], detail)
        detail["suggestion"] = "repeat the command with --context/--row-label/--column-header"
        return Proof(
            False,
            None,
            [
                f"quote occurs {len(quote_spans)} times in the fixture; without a row context "
                "the span is ambiguous, so the loader would refuse a verified row"
            ],
            detail,
        )

    detail["context"] = context
    context_spans = occurrence_spans(fixture_text, context)
    detail["context_occurrences"] = len(context_spans)
    if len(context_spans) != 1:
        return Proof(
            False,
            None,
            [
                f"context {context!r} occurs {len(context_spans)} times in the fixture; "
                "it must resolve exactly once"
            ],
            detail,
        )
    if len(quote_spans) < 2:
        detail["suggestion"] = "repeat the command without --context/--row-label/--column-header"
        return Proof(
            False,
            None,
            [
                f"quote is already globally unique ({len(quote_spans)} occurrence); a table-row "
                "context would be mislabelled and the loader rejects unique-with-context"
            ],
            detail,
        )
    block = row_block(fixture_text, context_spans[0])
    detail["row_block"] = list(block)
    in_block = inside(quote_spans, block)
    detail["quote_occurrences_in_block"] = len(in_block)
    if len(in_block) != 1:
        return Proof(
            False,
            None,
            [
                f"context {context!r} leaves {len(in_block)} quote occurrences in its row "
                "block; it must leave exactly one"
            ],
            detail,
        )
    if row_label:
        labels = occurrence_spans(fixture_text, row_label)
        label_in_block = len(inside(labels, block))
        detail["row_label"] = row_label
        detail["row_label_occurrences_in_block"] = label_in_block
        if label_in_block != 1:
            return Proof(
                False,
                None,
                [
                    f"row label {row_label!r} does not resolve exactly once inside the "
                    "context's row block"
                ],
                detail,
            )
    return Proof(True, "context_row", [], detail)


# ------------------------------------------------------------------- candidates


@dataclass(frozen=True)
class PrintedCandidate:
    """One selectable quote: a whole extracted line, optionally word-trimmed."""

    line_no: int  # 1-based over page.lines (blank separators excluded)
    line_text: str
    quote: str
    span: tuple[int, int]  # quote span inside the fixture text
    needle_span: tuple[int, int]

    def display(self) -> str:
        return (
            f"line {self.line_no:>3}  quote span [{self.span[0]}, {self.span[1]})  {self.quote!r}"
        )


def trim_words(line: str, trim_left: int, trim_right: int) -> str | None:
    words = line.strip().split()
    if trim_left < 0 or trim_right < 0 or trim_left + trim_right >= len(words):
        return None
    return " ".join(words[trim_left : len(words) - trim_right])


def find_candidates(
    page: Any,  # fmd.eval.pdfpage.PageText
    needle: str,
    *,
    trim_left: int = 0,
    trim_right: int = 0,
) -> list[PrintedCandidate]:
    """Every fixture line that contains ``needle`` (exact first, then canonical)."""
    spans = occurrence_spans(page.text, needle)
    candidates: list[PrintedCandidate] = []
    seen_lines: set[int] = set()
    for span in spans:
        line_no = None
        for index, (start, end) in enumerate(page.line_spans, start=1):
            if start <= span[0] < end:
                line_no = index
                break
        if line_no is None or line_no in seen_lines:
            continue
        seen_lines.add(line_no)
        line_text = page.lines[line_no - 1]
        quote = (
            trim_words(line_text, trim_left, trim_right)
            if (trim_left or trim_right)
            else (line_text.strip())
        )
        if not quote:
            continue
        quote_spans = occurrence_spans(page.text, quote)
        if not quote_spans:
            continue  # the trim removed the printed value; the candidate is unusable
        quote_span = min((s for s in quote_spans), key=lambda s: abs(s[0] - span[0]))
        candidates.append(
            PrintedCandidate(
                line_no=line_no,
                line_text=line_text,
                quote=quote,
                span=quote_span,
                needle_span=span,
            )
        )
    candidates.sort(key=lambda candidate: candidate.span[0])
    return candidates


# ----------------------------------------------------------------------- plan


@dataclass
class AddInputs:
    source: str
    page: int
    predicate: str
    value_raw: str
    unit: str | None
    printed_value: str | None = None
    printed_unit: str | None = None
    institution: str = ""
    programme: str = ""
    state: str | None = None
    entry_id: str | None = None
    context: str | None = None
    row_label: str | None = None
    column_header: str | None = None
    value_cell: str | None = None
    table_page: int | None = None
    source_url: str | None = None
    notes: str | None = None
    trim_left: int = 0
    trim_right: int = 0
    golden_dir: Path = Path("data/golden")
    root: Path = Path(".")
    dry_run: bool = False
    force: bool = False

    def validate(self) -> None:
        missing = [
            name
            for name, value in (
                ("--source", self.source),
                ("--page (1-based)", 1 if (isinstance(self.page, int) and self.page >= 1) else 0),
                ("--institution", self.institution),
                ("--programme", self.programme),
                ("--predicate", self.predicate),
                ("--value", self.value_raw),
            )
            if not value
        ]
        if missing:
            raise CuratorError(
                "missing required inputs: "
                + ", ".join(missing)
                + " (re-run with --interactive to be prompted)"
            )
        table = any((self.context, self.row_label, self.column_header, self.value_cell))
        if table and not self.context:
            raise CuratorError(
                "a table-row claim needs --context (the anchor cell, e.g. the institution line); "
                "--row-label/--column-header alone cannot scope the row block"
            )
        if table and not (self.row_label and self.column_header):
            raise CuratorError(
                "a table-row claim requires both --row-label and --column-header "
                "(the extractor records them as RowIdentity)"
            )
        if self.value_cell and not table:
            raise CuratorError("--value-cell only applies to a table-row claim (--context)")


@dataclass
class AddPlan:
    inputs: AddInputs
    value: Any
    needle: str
    fixture_text: str
    fixture_rel: str
    fixture_path: Path
    entry_id: str
    entry_path: Path
    candidates: list[PrintedCandidate]


def plan_add(inputs: AddInputs, page: Any) -> AddPlan:
    """Build everything that can be decided before a candidate is picked."""
    inputs.validate()
    value = parse_scalar(inputs.value_raw)
    needle = inputs.printed_value.strip() if inputs.printed_value else str(value)
    if not needle:
        raise CuratorError("--printed-value is empty; pass the form the document prints")

    root = inputs.root.resolve()
    golden_dir = inputs.golden_dir.resolve()
    entry_id = inputs.entry_id or slugify(inputs.institution)
    fixture_path = golden_dir / FIXTURES_DIRNAME / f"{entry_id}_page{page.page:02d}.txt"
    try:
        fixture_rel = fixture_path.relative_to(root).as_posix()
    except ValueError as exc:
        raise CuratorError(
            f"--golden-dir must live under --root ({root}) so the fixture can be recorded "
            f"repo-relative; got {golden_dir}"
        ) from exc
    entry_path = golden_dir / PROGRAMMES_DIRNAME / f"{entry_id}.yaml"
    candidates = find_candidates(
        page, needle, trim_left=inputs.trim_left, trim_right=inputs.trim_right
    )
    return AddPlan(
        inputs=inputs,
        value=value,
        needle=needle,
        fixture_text=page.text,
        fixture_rel=fixture_rel,
        fixture_path=fixture_path,
        entry_id=entry_id,
        entry_path=entry_path,
        candidates=candidates,
    )


def resolve_candidate(plan: AddPlan, pick: int | None) -> PrintedCandidate:
    """Deterministic pick: explicit --pick, else the single candidate, else refuse."""
    if not plan.candidates:
        raise CuratorError(
            f"the printed value {plan.needle!r} does not occur on page "
            f"{plan.inputs.page} of the extracted text; check --page, the expected value, "
            "or --printed-value"
        )
    if pick is not None:
        if not 1 <= pick <= len(plan.candidates):
            raise CuratorError(
                f"--pick {pick} is out of range; the page offers {len(plan.candidates)} "
                "candidate line(s)"
            )
        return plan.candidates[pick - 1]
    if len(plan.candidates) == 1:
        return plan.candidates[0]
    listing = "\n".join(f"  {index}: {c.display()}" for index, c in enumerate(plan.candidates, 1))
    raise CuratorError(
        f"the printed value {plan.needle!r} matches {len(plan.candidates)} lines; pass "
        f"--pick N (or --interactive):\n{listing}"
    )


